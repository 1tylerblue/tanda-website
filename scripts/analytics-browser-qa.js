async (page) => {
  const context = page.context();
  let leadMode = 'failure';
  let leadRequests = 0;

  const analyticsConfig = {
    enabled: true,
    projectKey: 'phc_browser_test',
    host: 'http://127.0.0.1:4175',
    uiHost: 'http://127.0.0.1:4175',
    environment: 'test',
    release: 'browser-qa',
    sessionRecordingEnabled: false,
    heatmapsEnabled: false,
    performanceSampleRate: 1,
    captureInternalTraffic: false,
  };

  await context.route('**/api/analytics-config', (route) => route.fulfill({
    status: 200,
    contentType: 'application/json',
    body: JSON.stringify(analyticsConfig),
  }));
  await context.route('**/static/1/array.js', (route) => route.fulfill({
    status: 200,
    contentType: 'application/javascript',
    body: `(() => {
      const ph = window.posthog;
      const init = ph && ph._i && ph._i[0];
      if (!ph || !init) return;
      window.__qaPostHogEvents = [];
      ph.capture = (event, properties) => window.__qaPostHogEvents.push({ event, properties });
      ph.opt_in_capturing = () => {};
      ph.opt_out_capturing = () => {};
      ph.startSessionRecording = () => {};
      if (init[1] && typeof init[1].loaded === 'function') init[1].loaded(ph);
    })();`,
  }));
  await context.route('**/api/travel-distance**', (route) => route.fulfill({
    status: 200,
    contentType: 'application/json',
    body: JSON.stringify({
      resolvedAddress: 'Synthetic test location',
      distanceKm: 12,
      travelBand: 'within_50km',
      travelFeeIncGst: 0,
    }),
  }));
  await context.route('**/api/giveaway/status', (route) => route.fulfill({
    status: 200,
    contentType: 'application/json',
    body: JSON.stringify({ entryCount: 0, entryTarget: 50, unlocked: false, campaignOpen: false }),
  }));
  await context.route('**/api/leads', async (route) => {
    leadRequests += 1;
    if (leadMode === 'failure') {
      await route.fulfill({
        status: 503,
        contentType: 'application/json',
        body: JSON.stringify({ error: 'Synthetic service unavailable' }),
      });
      return;
    }
    await route.fulfill({
      status: 201,
      contentType: 'application/json',
      body: JSON.stringify({
        analyticsLeadId: '8a763e5a-1478-49ab-92ce-17c792147382',
        recommendedEstimate: 275,
        recommendedEstimateIncGst: 302.5,
        recommendedEstimateLabel: '$302.50 inc GST',
        accuracyLevel: 'high',
        customerScope: ['Synthetic scope generated by the mocked QA response.'],
        eligibleForGiveaway: false,
        deliveryStatus: { email: 'Sent to tandaprocleaning@gmail.com' },
      }),
    });
  });
  for (const pattern of [
    '**://*.google-analytics.com/**',
    '**://*.googlesyndication.com/**',
    '**://*.googletagmanager.com/**',
    '**://googleads.g.doubleclick.net/**',
  ]) {
    await context.route(pattern, (route) => route.fulfill({ status: 204, body: '' }));
  }

  const captureEvents = async () => page.evaluate(() => Array.isArray(window.__qaPostHogEvents)
    ? window.__qaPostHogEvents.slice()
    : []);

  await page.goto('http://127.0.0.1:4175/index.html');
  await page.evaluate(() => {
    localStorage.clear();
    sessionStorage.clear();
    localStorage.setItem('tac_cookie_consent_v1', JSON.stringify({ state: 'accepted', timestamp: Date.now() }));
  });
  await page.reload();
  await page.waitForTimeout(800);

  const initialStatus = await page.evaluate(() => window.TandaAnalytics.getStatus());
  const initialEvents = await captureEvents();

  await page.evaluate(async () => {
    const clickSafely = (element) => {
      element.addEventListener('click', (event) => event.preventDefault(), { once: true });
      element.click();
    };
    const selectors = [
      '.service-card a[href]',
      '.package-card a[href]',
      'a[href^="tel:"]',
      'a[href^="mailto:"]',
      'a[href*="gallery"]',
      'a[href*="referrals"]',
      'a[href*="giveaway"]',
    ];
    Array.from(document.querySelectorAll(selectors.join(','))).slice(0, 100).forEach(clickSafely);
    const maxScroll = Math.max(0, document.documentElement.scrollHeight - innerHeight);
    for (const ratio of [0.1, 0.25, 0.5, 0.75, 0.9, 1]) {
      scrollTo(0, maxScroll * ratio);
      await new Promise((resolve) => setTimeout(resolve, 140));
    }
  });
  await page.waitForTimeout(350);

  await page.evaluate(() => {
    const form = document.getElementById('quoteForm');
    const setValue = (id, value) => {
      const field = document.getElementById(id);
      field.value = value;
      field.dispatchEvent(new Event('input', { bubbles: true }));
      field.dispatchEvent(new Event('change', { bubbles: true }));
    };
    setValue('firstName', 'Analytics Test Customer');
    setValue('phone', '0400 000 000');
    setValue('email', 'analytics.test@example.com');
    setValue('address', '1 Test Street, Brisbane');
    setValue('propertyType', 'Residential');
    setValue('storeys', '1');
    setValue('service', 'window-cleaning');
    const pricing = document.getElementById('pricingItemCode');
    pricing.value = Array.from(pricing.options).find((option) => option.value)?.value || '';
    pricing.dispatchEvent(new Event('change', { bubbles: true }));
    setValue('scopeQuantity', '8');
    setValue('serviceArea', 'Both');
    const agree = form.querySelector('input[name="agree"]');
    agree.checked = true;
    agree.dispatchEvent(new Event('change', { bubbles: true }));
    const back = form.querySelector('[data-mobile-quote-back]');
    if (back) back.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
  await page.waitForTimeout(700);

  for (const selector of [
    '.property-details-card',
    '.service-scope-card',
    '[data-quote-more-details], .quote-more-details',
    '.quote-notes-card',
    '[data-quote-inclusions]',
  ]) {
    const target = page.locator(selector).first();
    if (await target.count() && await target.isVisible()) {
      await target.scrollIntoViewIfNeeded();
      await page.waitForTimeout(180);
    }
  }

  await page.evaluate(() => {
    const input = document.getElementById('photoUpload');
    const failedTransfer = new DataTransfer();
    failedTransfer.items.add(new File([new Uint8Array(4 * 1024 * 1024 + 1)], 'customer@example.com.jpg', { type: 'image/jpeg' }));
    input.files = failedTransfer.files;
    input.dispatchEvent(new Event('change', { bubbles: true }));
    const passedTransfer = new DataTransfer();
    passedTransfer.items.add(new File([new Uint8Array([1, 2, 3, 4])], '1 Test Street.jpg', { type: 'image/jpeg' }));
    input.files = passedTransfer.files;
    input.dispatchEvent(new Event('change', { bubbles: true }));
  });
  await page.waitForTimeout(250);

  await page.evaluate(() => {
    const form = document.getElementById('quoteForm');
    form.requestSubmit();
    form.requestSubmit();
  });
  await page.waitForTimeout(800);
  const eventsAfterFailure = await captureEvents();
  const failedMessage = await page.locator('#formMessage').textContent();
  const failureLeadRequests = leadRequests;
  const quoteAdsConversionsAfterFailure = await page.evaluate(() => (window.dataLayer || [])
    .map((entry) => Array.from(entry || []))
    .filter((entry) => entry[0] === 'event'
      && entry[1] === 'conversion'
      && entry[2]
      && entry[2].send_to === 'AW-11132030271/8PYfCNyuw9QcEL-albwp').length);

  leadMode = 'success';
  await page.evaluate(() => document.getElementById('quoteForm').requestSubmit());
  await page.waitForTimeout(900);
  const eventsAfterSuccess = await captureEvents();
  const successMessage = await page.locator('#formMessage').textContent();
  const quoteAdsConversionsAfterSuccess = await page.evaluate(() => (window.dataLayer || [])
    .map((entry) => Array.from(entry || []))
    .filter((entry) => entry[0] === 'event'
      && entry[1] === 'conversion'
      && entry[2]
      && entry[2].send_to === 'AW-11132030271/8PYfCNyuw9QcEL-albwp').length);

  const serializedEvents = JSON.stringify(eventsAfterSuccess).toLowerCase();
  const piiLeaks = [
    'analytics test customer',
    '0400 000 000',
    'analytics.test@example.com',
    '1 test street',
    'customer@example.com.jpg',
  ].filter((value) => serializedEvents.includes(value));

  const viewports = [];
  for (const viewport of [
    { name: 'desktop', width: 1440, height: 900 },
    { name: 'tablet', width: 820, height: 1180 },
    { name: 'mobile', width: 390, height: 844 },
  ]) {
    await page.setViewportSize({ width: viewport.width, height: viewport.height });
    await page.goto('http://127.0.0.1:4175/index.html');
    await page.waitForTimeout(350);
    viewports.push(await page.evaluate((name) => ({
      name,
      horizontalOverflow: document.documentElement.scrollWidth > document.documentElement.clientWidth + 1,
      quoteVisible: Boolean(document.getElementById('quoteForm')),
      analyticsLoaded: Boolean(window.TandaAnalytics),
    }), viewport.name));
  }

  await page.evaluate(() => window.TandaAnalytics.markInternal(true));
  await page.reload();
  await page.waitForTimeout(400);
  const internalStatus = await page.evaluate(() => window.TandaAnalytics.getStatus());
  const internalEvents = await captureEvents();
  await page.evaluate(() => {
    localStorage.setItem('tac_internal_traffic_v1', JSON.stringify(false));
    localStorage.setItem('tac_cookie_consent_v1', JSON.stringify({ state: 'denied', timestamp: Date.now() }));
  });
  await page.reload();
  await page.waitForTimeout(400);
  const deniedStatus = await page.evaluate(() => window.TandaAnalytics.getStatus());
  const deniedEvents = await captureEvents();

  const browser = context.browser();
  const blockedContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  await blockedContext.route('**/api/analytics-config', (route) => route.fulfill({
    status: 200,
    contentType: 'application/json',
    body: JSON.stringify(analyticsConfig),
  }));
  await blockedContext.route('**/static/1/array.js', (route) => route.abort('blockedbyclient'));
  for (const pattern of [
    '**://*.google-analytics.com/**',
    '**://*.googlesyndication.com/**',
    '**://*.googletagmanager.com/**',
    '**://googleads.g.doubleclick.net/**',
  ]) {
    await blockedContext.route(pattern, (route) => route.fulfill({ status: 204, body: '' }));
  }
  const blockedPage = await blockedContext.newPage();
  await blockedPage.goto('http://127.0.0.1:4175/index.html');
  await blockedPage.evaluate(() => localStorage.setItem('tac_cookie_consent_v1', JSON.stringify({ state: 'accepted', timestamp: Date.now() })));
  await blockedPage.reload();
  await blockedPage.waitForTimeout(500);
  const blockedResult = await blockedPage.evaluate(() => ({
    status: window.TandaAnalytics.getStatus(),
    quoteExists: Boolean(document.getElementById('quoteForm')),
    bodyVisible: document.body.getBoundingClientRect().height > 0,
  }));
  await blockedContext.close();

  const dntContext = await browser.newContext();
  await dntContext.addInitScript(() => Object.defineProperty(navigator, 'doNotTrack', { configurable: true, get: () => '1' }));
  await dntContext.route('**/api/analytics-config', (route) => route.fulfill({
    status: 200,
    contentType: 'application/json',
    body: JSON.stringify(analyticsConfig),
  }));
  for (const pattern of [
    '**://*.google-analytics.com/**',
    '**://*.googlesyndication.com/**',
    '**://*.googletagmanager.com/**',
    '**://googleads.g.doubleclick.net/**',
  ]) {
    await dntContext.route(pattern, (route) => route.fulfill({ status: 204, body: '' }));
  }
  const dntPage = await dntContext.newPage();
  await dntPage.goto('http://127.0.0.1:4175/index.html');
  await dntPage.evaluate(() => localStorage.setItem('tac_cookie_consent_v1', JSON.stringify({ state: 'accepted', timestamp: Date.now() })));
  await dntPage.reload();
  await dntPage.waitForTimeout(400);
  const dntResult = await dntPage.evaluate(() => ({
    status: window.TandaAnalytics.getStatus(),
    eventCount: Array.isArray(window.posthog)
      ? window.posthog.filter((item) => Array.isArray(item) && item[0] === 'capture').length
      : 0,
  }));
  await dntContext.close();

  const eventNames = eventsAfterSuccess.map((entry) => entry.event);
  const eventCounts = Object.fromEntries(Array.from(new Set(eventNames)).sort().map((name) => [
    name,
    eventNames.filter((eventName) => eventName === name).length,
  ]));

  return {
    initialStatus,
    initialPageViewedCount: initialEvents.filter((entry) => entry.event === 'page_viewed').length,
    eventCounts,
    scrollMilestones: eventsAfterSuccess
      .filter((entry) => entry.event === 'scroll_depth_reached')
      .map((entry) => entry.properties.scroll_percent),
    failureHadSubmittedEvent: eventsAfterFailure.some((entry) => entry.event === 'quote_submitted'),
    failureHadFailureEvent: eventsAfterFailure.some((entry) => entry.event === 'quote_submission_failed'),
    successfulSubmitCount: eventsAfterSuccess.filter((entry) => entry.event === 'quote_submitted').length,
    leadRequests,
    failureLeadRequests,
    quoteAdsConversionsAfterFailure,
    quoteAdsConversionsAfterSuccess,
    failedMessagePresent: /estimate is shown|could not|unavailable/i.test(failedMessage || ''),
    successMessagePresent: /sent to the t & a team/i.test(successMessage || ''),
    piiLeaks,
    viewports,
    internal: { status: internalStatus, eventCount: internalEvents.length },
    denied: { status: deniedStatus, eventCount: deniedEvents.length },
    blockedPostHog: blockedResult,
    doNotTrack: dntResult,
  };
}
